function verification = verify_results()
%VERIFY_RESULTS Check persisted outputs for leakage and accounting errors.

projectRoot = fileparts(mfilename('fullpath'));
addpath(fullfile(projectRoot, 'config'));
addpath(fullfile(projectRoot, 'src'));
cfg = default_config();
folder = fullfile(cfg.paths.outputs, 'modeling');

foldManifest = readtable(fullfile(folder, 'fold_manifest.csv'), 'TextType', 'string');
participantFolds = readtable( ...
    fullfile(folder, 'participant_fold_assignment.csv'));
predictions = readtable(fullfile(folder, 'oof_predictions.csv'), 'TextType', 'string');
confusionTable = readtable(fullfile(folder, 'confusion_counts.csv'));
foldSupport = readtable(fullfile(folder, 'fold_class_support.csv'));
ablation = readtable(fullfile(folder, 'band_ablation.csv'), 'TextType', 'string');
ablationFolds = readtable( ...
    fullfile(folder, 'band_ablation_fold_metrics.csv'), 'TextType', 'string');
permutations = readtable( ...
    fullfile(folder, 'structured_permutation_baseline.csv'));
metrics = readtable(fullfile(folder, 'metrics.csv'), 'TextType', 'string');
samplingGroupMetrics = readtable( ...
    fullfile(folder, 'sampling_rate_group_metrics.csv'));
sensitivityFolder = fullfile(cfg.paths.outputs, 'sampling_rate_sensitivity');
sensitivityPredictions = readtable( ...
    fullfile(sensitivityFolder, 'oof_predictions_all_256.csv'), 'TextType', 'string');
sensitivityMetrics = readtable( ...
    fullfile(sensitivityFolder, 'metrics.csv'), 'TextType', 'string');
durationFolder = fullfile(cfg.paths.outputs, 'duration_exclusion_sensitivity');
durationPredictions = readtable(fullfile( ...
    durationFolder, 'oof_predictions_structural_only.csv'), 'TextType', 'string');
durationMetrics = readtable( ...
    fullfile(durationFolder, 'metrics.csv'), 'TextType', 'string');
durationAddedTrials = readtable( ...
    fullfile(durationFolder, 'added_trials.csv'), 'TextType', 'string');
audit = readtable(fullfile(cfg.paths.outputs, 'audit', 'data_audit.csv'), ...
    'TextType', 'string');
runManifest = jsondecode(fileread(fullfile(folder, 'run_manifest.json')));

assert(height(foldManifest) == height(predictions), ...
    'Fold manifest and OOF prediction row counts differ.');
assert(numel(unique(foldManifest.trial_id)) == height(foldManifest), ...
    'A trial ID appears more than once in the fold manifest.');
assert(isequal(sort(foldManifest.trial_id), sort(predictions.trial_id)), ...
    'Fold manifest and OOF predictions do not contain the same trials.');

participants = unique(foldManifest.participant_id);
for participantIndex = 1:numel(participants)
    rows = foldManifest.participant_id == participants(participantIndex);
    assert(isscalar(unique(foldManifest.fold_id(rows))), ...
        'A participant appears in multiple outer folds.');
end

assert(all(ismember(predictions.true_condition_id, cfg.data.expectedEmotionIds)), ...
    'OOF truth contains an unknown condition ID.');
assert(all(ismember(predictions.predicted_condition_id, cfg.data.expectedEmotionIds)), ...
    'OOF predictions contain an unknown condition ID.');

storedConfusion = confusionTable{:, 2:end};
recomputed = compute_classification_metrics( ...
    predictions.true_condition_id, predictions.predicted_condition_id, ...
    cfg.data.expectedEmotionIds);
assert(isequal(storedConfusion, recomputed.confusionMatrix), ...
    'Stored confusion matrix does not match OOF predictions.');
assert(sum(storedConfusion, 'all') == height(predictions), ...
    'Confusion-matrix total does not equal the OOF trial count.');

assert(all(foldSupport{:, 2:end} > 0, 'all'), ...
    'At least one held-out fold lacks a condition.');
assert(height(permutations) == cfg.permutation.numRepeats, ...
    'Structured permutation count differs from configuration.');
assert(height(ablation) == numel(cfg.bands.names) + 1, ...
    'Band-ablation summary lacks a required variant.');
assert(height(ablationFolds) == ...
    (numel(cfg.bands.names) + 1) * cfg.cv.numFolds, ...
    'Band-ablation fold table is not fully paired.');

modelRow = metrics.model == "fourier_linear_ecoc";
assert(sum(modelRow) == 1 && all(isfinite(metrics{modelRow, 2:4}), 'all'), ...
    'Primary model metrics are missing or non-finite.');
assert(isequal(predictions.trial_id, sensitivityPredictions.trial_id), ...
    'Sampling-rate sensitivity does not use the identical trial order.');
assert(isequal(predictions.fold_id, sensitivityPredictions.fold_id), ...
    'Sampling-rate sensitivity does not reuse the primary folds.');
assert(height(sensitivityMetrics) == 2 && ...
    all(isfinite(sensitivityMetrics{:, 2:4}), 'all'), ...
    'Sampling-rate sensitivity metrics are incomplete.');

recomputedSamplingGroups = compute_sampling_group_metrics( ...
    predictions.true_condition_id, predictions.predicted_condition_id, ...
    predictions.participant_id, foldManifest.sampling_rate_hz, ...
    cfg.data.expectedEmotionIds);
assert(isequal(samplingGroupMetrics{:, 1:3}, ...
    recomputedSamplingGroups{:, 1:3}), ...
    'Sampling-rate subgroup counts do not match OOF predictions.');
assert(max(abs(samplingGroupMetrics{:, 4:6} - ...
    recomputedSamplingGroups{:, 4:6}), [], 'all') < 1e-12, ...
    'Sampling-rate subgroup metrics do not match OOF predictions.');
assert(sum(samplingGroupMetrics.trial_count) == height(predictions), ...
    'Sampling-rate subgroup trial counts do not cover all OOF predictions.');

expectedAddedTrials = sum(logical(audit.structural_ready) & ...
    logical(audit.duration_outlier));
assert(height(durationAddedTrials) == expectedAddedTrials, ...
    'Duration sensitivity did not add every structural duration outlier.');
assert(height(durationPredictions) == height(predictions) + expectedAddedTrials, ...
    'Duration-sensitivity prediction count is inconsistent.');
assert(all(ismember(predictions.trial_id, durationPredictions.trial_id)), ...
    'Duration sensitivity dropped a primary-analysis trial.');
assert(isequal(sort(setdiff(durationPredictions.trial_id, predictions.trial_id)), ...
    sort(durationAddedTrials.trial_id)), ...
    'Duration-sensitivity added-trial table is inconsistent.');
[knownDurationParticipant, durationFoldLocation] = ismember( ...
    durationPredictions.participant_id, participantFolds.participant_id);
assert(all(knownDurationParticipant) && isequal(durationPredictions.fold_id, ...
    participantFolds.fold_id(durationFoldLocation)), ...
    'Duration sensitivity does not reuse primary participant folds.');
assert(height(durationMetrics) == 2 && ...
    all(isfinite(durationMetrics{:, 2:5}), 'all'), ...
    'Duration-exclusion sensitivity metrics are incomplete.');
primaryDurationRow = durationMetrics.analysis == ...
    "primary_5_percent_duration_rule";
structuralDurationRow = durationMetrics.analysis == ...
    "structural_only_exclusion";
assert(sum(primaryDurationRow) == 1 && sum(structuralDurationRow) == 1, ...
    'Duration-sensitivity comparison rows are missing or duplicated.');
assert(durationMetrics.trial_count(primaryDurationRow) == height(predictions) && ...
    durationMetrics.trial_count(structuralDurationRow) == ...
    height(durationPredictions), ...
    'Duration-sensitivity metric row counts are inconsistent.');
assert(max(abs(durationMetrics{primaryDurationRow, 3:5} - ...
    metrics{modelRow, 2:4}), [], 'all') < 1e-12, ...
    'Duration-sensitivity primary metrics do not match current modeling output.');
recomputedDurationMetrics = compute_classification_metrics( ...
    durationPredictions.true_condition_id, ...
    durationPredictions.predicted_condition_id, cfg.data.expectedEmotionIds);
storedStructuralMetrics = durationMetrics{structuralDurationRow, 3:5};
expectedStructuralMetrics = [recomputedDurationMetrics.macroF1, ...
    recomputedDurationMetrics.balancedAccuracy, recomputedDurationMetrics.accuracy];
assert(max(abs(storedStructuralMetrics - expectedStructuralMetrics), [], 'all') < 1e-12, ...
    'Duration-sensitivity metrics do not match its OOF predictions.');

for outputIndex = 1:numel(runManifest.outputs)
    outputPath = fullfile(folder, runManifest.outputs(outputIndex).outputName);
    assert(isfile(outputPath), 'Run-manifest output is missing: %s', outputPath);
    observedHash = sha256_file(string(outputPath));
    assert(observedHash == string(runManifest.outputs(outputIndex).outputSha256), ...
        'Run-manifest hash mismatch: %s', outputPath);
end

verification = struct();
verification.trialCount = height(predictions);
verification.participantCount = numel(participants);
verification.foldCount = numel(unique(foldManifest.fold_id));
verification.conditionCount = numel(unique(predictions.true_condition_id));
verification.confusionTotal = sum(storedConfusion, 'all');
verification.permutationCount = height(permutations);
verification.ablationFoldRows = height(ablationFolds);
verification.samplingSensitivityMatched = true;
verification.samplingGroupCount = height(samplingGroupMetrics);
verification.durationSensitivityAddedTrials = expectedAddedTrials;
verification.outputHashesVerified = numel(runManifest.outputs);
verification.passed = true;

fprintf(['Verified %d OOF trials, %d participants, %d folds, %d conditions, ' ...
    '%d permutations, %d paired ablation-fold rows, and %d duration ' ...
    'sensitivity additions.\n'], ...
    verification.trialCount, verification.participantCount, ...
    verification.foldCount, verification.conditionCount, ...
    verification.permutationCount, verification.ablationFoldRows, ...
    verification.durationSensitivityAddedTrials);
end

